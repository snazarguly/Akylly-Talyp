package com.example.features.offline_ai.inference

import android.content.Context
import kotlinx.coroutines.flow.Flow

/**
 * Interface for on-device LLM inference.
 * Supports direct loading from APK assets for zero-copy efficiency.
 */
interface LocalInferenceEngine {

    /**
     * Current status of the model.
     */
    val state: Flow<ModelState>

    /**
     * Initializes the engine by loading the model directly from APK assets.
     * @param context Android context to access assets.
     * @param assetPath Path within the assets folder (e.g., "models/Qwen3-4B-Instruct-Q4_K_M.gguf").
     */
    suspend fun initializeFromAssets(context: Context, assetPath: String, config: InferenceConfig): Result<Unit>

    /**
     * Generates a streaming response from the LLM.
     */
    fun generateResponse(prompt: String): Flow<InferenceToken>

    /**
     * Stops the current generation.
     */
    fun stop()

    /**
     * Unloads the model and releases native resources.
     */
    fun release()
}

/**
 * Represents a single token (or piece of text) generated by the model.
 */
data class InferenceToken(
    val text: String,
    val isLast: Boolean = false,
    val tokensPerSecond: Double = 0.0
)

/**
 * Lifecycle states for the local model.
 */
enum class ModelState {
    UNINITIALIZED,
    LOADING,
    READY,
    ERROR,
    GENERATING
}
